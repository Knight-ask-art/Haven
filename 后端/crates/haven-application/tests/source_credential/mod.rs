//! 自定义源凭据生命周期用例的内聚分组。
//!
//! - [`fixtures`]：共享夹具（真实 SQLite + 真实 `SettingsUoW`、可注入失败/可确定交错的
//!   外部凭据端口、落库负载读写）。没有断言。
//! - [`lifecycle`]：版本槽分配、旧槽退休、清除、外部写入失败、历史引用读取与轮换、
//!   伪造/串源引用、以及「采纳失败 + 补偿删除/义务登记失败」时的持久化所有权。
//!   都在**公开装配面**上驱动。
//! - [`races`]：并发写入者、写入者与删除/清除的确定性交错（会合点或外部写入期间的
//!   真实并发用例，不用 sleep）。
//! - [`cleanup`]：持久化清理义务的有界批量、幂等、跨重启重试、暂存槽过期与守卫、
//!   清理队列写满时的容量感知退休与公平轮转、缓存清理的来源在用守卫，以及同一引用
//!   不同归属来源的义务按**精确身份**登记与出队（伪造条目既吞不掉、也不被连带删除）。
//! - [`initialization`]：`sources` 段的首次写入初始化（第一次 `list` 之前的显式选择）。

pub mod cleanup;
pub mod fixtures;
pub mod initialization;
pub mod lifecycle;
pub mod races;
